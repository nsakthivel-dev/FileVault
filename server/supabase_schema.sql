-- Service Role full access policies (for backend serverless lambdas using service_role key)
DROP POLICY IF EXISTS "Service role full access to users" ON public.users;
CREATE POLICY "Service role full access to users" ON public.users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access to documents" ON public.documents;
CREATE POLICY "Service role full access to documents" ON public.documents FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access to shares" ON public.shares;
CREATE POLICY "Service role full access to shares" ON public.shares FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access to audit_logs" ON public.audit_logs;
CREATE POLICY "Service role full access to audit_logs" ON public.audit_logs FOR ALL USING (true) WITH CHECK (true);

-- Authenticated user policies (direct Supabase client calls)
DROP POLICY IF EXISTS "Users can read/write own user record" ON public.users;
CREATE POLICY "Users can read/write own user record" ON public.users 
  FOR ALL USING (auth.uid()::text = id) WITH CHECK (auth.uid()::text = id);

DROP POLICY IF EXISTS "Users can read/write own documents" ON public.documents;
CREATE POLICY "Users can read/write own documents" ON public.documents 
  FOR ALL USING (auth.uid()::text = owner_id) WITH CHECK (auth.uid()::text = owner_id);

DROP POLICY IF EXISTS "Users can read/write own shares" ON public.shares;
CREATE POLICY "Users can read/write own shares" ON public.shares 
  FOR ALL USING (auth.uid()::text = owner_id) WITH CHECK (auth.uid()::text = owner_id);

DROP POLICY IF EXISTS "Public can view active shares" ON public.shares;
CREATE POLICY "Public can view active shares" ON public.shares 
  FOR SELECT USING (status = 'ACTIVE');

DROP POLICY IF EXISTS "Users can view own audit logs" ON public.audit_logs;
CREATE POLICY "Users can view own audit logs" ON public.audit_logs 
  FOR SELECT USING (auth.uid()::text = user_id);
